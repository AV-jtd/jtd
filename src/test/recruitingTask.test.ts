import { describe, it, expect } from "vitest";
import { looksLikeRecruiting as hr } from "../../supabase/functions/_shared/recruitingTask";

describe("бот: задача на подбор людей → HR", () => {
  it.each([
    "Поиск руководителя по брендингу и/или рекламе. Асия",
    "Нанять Администратора",
    "Найти администратора, координатора",
    "Провести собеседования с потенциальными сборщиками",
    "Поиск и наем ответственного за управление ассортиментом — менеджер",
    "Найм и обучение локального аналитика",
    "Вакансия бренд-менеджер, разместить на hh",
    "Подбор водителя на Киров до пятницы",
  ])("HR: %s", (t) => expect(hr(t)).toBe(true));

  it.each([
    "Поиск потенциальных поставщиков оборудования",
    "Поиск эквивалента производства РФ",
    "Поиск агентств пермь",
    "Тендер на поиск застройщика по стенду",
    "Купить картриджи до пятницы",
    "Позвонить руководителю Ленты по образцам",
    "Запуск таргета по вакансиям",
  ])("не HR: %s", (t) => expect(hr(t)).toBe(false));
});
