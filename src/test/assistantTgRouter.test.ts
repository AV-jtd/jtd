import { describe, it, expect } from "vitest";
import { looksLikeAssistantRequest as ask, isAcknowledgement as ack } from "../../supabase/functions/_shared/assistantTgRouter";

describe("бот: вопрос ассистенту или задача", () => {
  it.each([
    "Что у меня горит на неделе?",
    "что у меня горит",
    "Какие задачи просрочены",
    "Когда срок по КП для Дикси",
    "Сколько задач у Марии",
    "покажи мои задачи на завтра",
    "Перенеси задачу про образцы на пятницу",
    "Назначь КП Ашан на Ирину",
    "Найди задачу про сосиски",
    "ИИ, сделай сводку по проекту",
    "Помощник: что нового в Продажах мечты",
    "Можно ли перенести тендер Ленты",
    "У кого больше всего просрочки",
    "а что по Бристолю?",
    "Позвонить в Магнит насчёт образцов?",
    "Сможешь сделать каскадные связи в проекте оборудование",
    "Можешь перенести мои задачи на завтра",
    "Создай задачу",
    "Создай задачу позвонить в Ленту в пятницу",
  ])("вопрос → ассистент: %s", (t) => expect(ask(t)).toBe(true));

  it.each([
    "Купить картриджи до пятницы",
    "Позвонить в Магнит насчёт образцов",
    "Найти подрядчика на стенд",
    "Проверить счёт от поставщика",
    "КП для Ашана до 10.10",
    "Отправить образцы в Ленту @ivan",
    "!Срочно согласовать макет",
    "Перенести встречу с Бакиным",
    "Сделать презентацию к пятнице",
    "/ai что горит",
  ])("задача → как раньше: %s", (t) => expect(ask(t)).toBe(false));

  it("список из нескольких строк — задачи, даже с вопросом", () => {
    expect(ask("Что по Бристолю?\nКупить картриджи")).toBe(false);
  });

  it("пересланное и голосовое — всегда задачи", () => {
    expect(ask("Что по Бристолю?", { forwarded: true })).toBe(false);
    expect(ask("Что по Бристолю?", { voice: true })).toBe(false);
  });

  it("длинный текст — не вопрос ассистенту", () => {
    expect(ask("Что " + "очень ".repeat(120) + "?")).toBe(false);
  });

  it.each(["да", "Да!", "ок", "Спасибо", "спасибо!)", "понял", "👍"])("подтверждение — не задача: %s", (t) => expect(ack(t)).toBe(true));
  it.each(["да, перенеси на пятницу", "Купить картриджи", "Ок задача на завтра"])("не подтверждение: %s", (t) => expect(ack(t)).toBe(false));
});
