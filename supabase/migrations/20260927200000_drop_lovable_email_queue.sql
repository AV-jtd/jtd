-- Удаление очереди писем — наследия облака Lovable.
--
-- Что это было. Асинхронная отправка писем авторизации:
--   GoTrue → auth-email-hook → enqueue_email → pgmq → process-email-queue
--          → sendLovableEmail (пакет @lovable.dev/email-js, ключ LOVABLE_API_KEY)
-- То есть письма подтверждения, восстановления и приглашений уходили через
-- облако Lovable, пока проект там жил.
--
-- Почему удаляем (решение владельца 27.09.2026):
--
--  * Оживить нельзя. Отправка завязана на облако Lovable, от которого проект
--    ушёл. По журналу public.email_send_log: 10 писем ушло с 14.05 по 04.06,
--    дальше только pending (31) и dlq (21), последняя запись 29.06.
--  * Не подключено. Переменных GOTRUE_HOOK_* в контейнере авторизации нет
--    вообще, то есть хук не настроен и GoTrue шлёт напрямую по SMTP. Вся
--    цепочка висит отключённой: ни одного вызова email_queue_dispatch или
--    enqueue_email из триггеров, других функций, заданий cron или кода
--    приложения — проверено.
--  * Мешает. Мёртвый код выглядит работающей рассылкой: кто-нибудь решит, что
--    письма отправляются или что их легко включить, а там зашитый адрес чужого
--    облака и отсутствующий секрет.
--  * Почта чиниться не будет. Решение от 27.09: канал возврата доступа —
--    Telegram-бот, письма с сайта не восстанавливаем.
--
-- Что НЕ удаляется: таблицы истории public.email_send_log (62 строки),
-- email_send_state, suppressed_emails, email_unsubscribe_tokens. Они маленькие
-- и хранят запись о том, что происходило, — это не машинерия, а свидетельство.
--
-- Про очереди pgmq. Их 107 при 36 сообщениях суммарно и 10 МБ на диске.
-- Значительная часть — следы автоматической проверки на уязвимости от
-- 26.08.2026: имена вида q_sqli_test (внутри {"probe": "'"}), q_bola_probe_*,
-- q_bfla_poc_*, q_test_probe_queue, а также мусор вроде q_123, q_x и очередь с
-- пустым именем. Нашего в них нет.
--
-- Обратимость: всё есть в дампе перед работой (каталог копий,
-- before-gotrue-upgrade_20260927_*.dump, 95 МБ).

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Функции очереди
-- ---------------------------------------------------------------------------
DROP FUNCTION IF EXISTS public.email_queue_dispatch();
DROP FUNCTION IF EXISTS public.email_queue_wake();
DROP FUNCTION IF EXISTS public.enqueue_email(text, jsonb);
DROP FUNCTION IF EXISTS public.read_email_batch(text, integer, integer);
DROP FUNCTION IF EXISTS public.delete_email(text, bigint);
DROP FUNCTION IF EXISTS public.move_to_dlq(text, text, bigint, jsonb);

-- ---------------------------------------------------------------------------
-- 2. Все очереди pgmq
-- ---------------------------------------------------------------------------
-- Через pgmq.drop_queue, а не удалением таблиц: функция убирает и очередь
-- q_<имя>, и архив a_<имя>, и запись в pgmq.meta. Ручное удаление таблиц
-- оставило бы метаданные, и список очередей врал бы.
--
-- Имена берутся из pgmq.meta, а не перечисляются: их 107, и список менялся бы
-- при каждом прогоне сканера. Проверено перед удалением, что pgmq не
-- используется больше нигде — ни в других функциях, ни в cron, ни в коде.
DO $$
DECLARE r record; dropped int := 0;
BEGIN
  FOR r IN SELECT queue_name FROM pgmq.meta ORDER BY queue_name LOOP
    PERFORM pgmq.drop_queue(r.queue_name);
    dropped := dropped + 1;
  END LOOP;
  RAISE NOTICE 'удалено очередей: %', dropped;
END $$;

COMMIT;
