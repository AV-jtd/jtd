-- Признак «проект с планом» или «операционный поток».
--
-- Зачем. В базе не было способа отличить проект, который живёт по плану (вехи,
-- связи, критический путь), от операционного потока поручений — например
-- «Продажи мечты»: 148 задач, ни одной вехи, задачи прилетают репликами из
-- Telegram. И то и другое — project_type = 'standard' с view_mode = 'container'.
-- Помощник в разговоре не мог знать, о чём его спрашивают, и разбирал поток по
-- гантовым меркам.
--
-- Почему отдельная колонка, а не новое значение project_type: тип фигурирует в
-- десятках фильтров приложения, и новое значение выкинуло бы такие проекты из
-- списков. Колонка — добавление, она ничего не ломает.
--
-- Почему НЕ вывод по отсутствию вех (обсуждалось с владельцем 30.09): это вывод
-- по отсутствию данных, и он ломается в обе стороны. Настоящий проект в первый
-- день тоже без вех; операционному потоку однажды поставят веху «выставка
-- 1 марта», и он молча перестанет считаться потоком. Поведение, меняющееся само
-- вслед за данными, — тот же класс тихих ошибок, что дрифт и счётчики.
--
-- NULL значит «не задано» — это честное третье состояние: помощник тогда не
-- угадывает, а говорит, что признак не проставлен. Проставляет владелец
-- ползунком, массовой простановки задним числом нет.

ALTER TABLE public.task_groups
  ADD COLUMN IF NOT EXISTS work_mode text;

ALTER TABLE public.task_groups
  DROP CONSTRAINT IF EXISTS task_groups_work_mode_check;

ALTER TABLE public.task_groups
  ADD CONSTRAINT task_groups_work_mode_check
  CHECK (work_mode IS NULL OR work_mode IN ('plan', 'flow'));

COMMENT ON COLUMN public.task_groups.work_mode IS
  'plan — проект с планом (вехи, связи, базовый план); flow — операционный поток поручений; NULL — не задано. Ставится вручную, не выводится из данных.';

-- Частичный индекс: потоки спрашивают отдельно (автофиксация, разбор в
-- помощнике), а их заметно меньше, чем проектов.
CREATE INDEX IF NOT EXISTS task_groups_work_mode_idx
  ON public.task_groups (work_mode)
  WHERE work_mode IS NOT NULL;
