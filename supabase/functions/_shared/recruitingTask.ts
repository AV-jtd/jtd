// Задачи на подбор людей — в проект «HR» с меткой и шагами (решение владельца
// 06.10.2026). Образец шагов — задача «Нанять Администратора» в проекте HR.
//
// Подбор = действие найма + должность. Одного «поиск» мало: «Поиск
// поставщиков», «поиск агентств» — не HR. Должность — по корню слова, чтобы
// ловить падежи («руководителя», «сборщиками»).

const ACTION = /(поиск|подбор|найм|на[её]м|нанять|наня|найти|ищем|ищу|ваканси|кандидат|собеседовани|рекрут|закрыть позици)/iu;
const ROLE = /(руководител|менеджер|специалист|директор|администратор|координатор|аналитик|бухгалтер|дизайнер|технолог|пов[ао]р|продав|водител|оператор|сотрудник|маркетолог|юрист|ассистент|помощник|секретар|инженер|мерчендайзер|супервайзер|торгов\S* представител|кладовщик|грузчик|сборщик|стаж[её]р|рекрутер|hr\b|логист|экономист|программист|разработчик|smm|таргетолог|копирайтер|бренд-?менеджер|контент|фотограф|видеограф|уборщ|охранник|упаковщик|комплектовщик|мастер|бригадир|начальник|заместител|ведущ\S* специалист|шеф|су-?шеф|кассир|официант|бариста|курьер|диспетчер|архитектор|тестировщик|data|аналитик)/iu;

export function looksLikeRecruiting(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  return ACTION.test(t) && ROLE.test(t);
}

